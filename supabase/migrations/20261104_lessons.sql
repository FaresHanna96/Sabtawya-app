-- Weekly lesson programme (from برنامج معدل.xlsx).
-- One lesson per Coptic month + week (1-4) + grade (3-6); the pulpit and hymns
-- are shared by every grade. A Saturday maps to its Coptic month and week in
-- the app (week = ceil(coptic day / 7)); days 29-30 have no lesson.
create table if not exists public.lessons (
  id           uuid primary key default gen_random_uuid(),
  coptic_month smallint not null check (coptic_month between 1 and 12),
  week         smallint not null check (week between 1 and 4),
  grade        smallint not null check (grade between 3 and 6),
  title        text not null,
  page         integer,
  unique (coptic_month, week, grade)
);

create table if not exists public.lesson_extras (
  coptic_month smallint not null check (coptic_month between 1 and 12),
  week         smallint not null check (week between 1 and 4),
  pulpit       text,
  hymns        text,
  primary key (coptic_month, week)
);

alter table public.lessons enable row level security;
alter table public.lesson_extras enable row level security;

drop policy if exists lessons_select on public.lessons;
create policy lessons_select on public.lessons
  for select to authenticated using (true);
drop policy if exists lessons_write on public.lessons;
create policy lessons_write on public.lessons
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists lesson_extras_select on public.lesson_extras;
create policy lesson_extras_select on public.lesson_extras
  for select to authenticated using (true);
drop policy if exists lesson_extras_write on public.lesson_extras;
create policy lesson_extras_write on public.lesson_extras
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

grant select on public.lessons, public.lesson_extras to authenticated;
grant insert, update, delete on public.lessons, public.lesson_extras to authenticated;

delete from public.lessons;
delete from public.lesson_extras;

